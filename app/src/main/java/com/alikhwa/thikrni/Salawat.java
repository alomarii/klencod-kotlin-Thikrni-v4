package com.alikhwa.thikrni;

import java.util.Random;

/** صيغ الصلاة على النبي صلى الله عليه وسلم. */
public final class Salawat {
    private Salawat() {}

    static final String[] LIST = {
            "اللهم صلِّ وسلِّم وبارك على سيدنا محمد وعلى آله وصحبه أجمعين",
            "صلى الله عليه وسلم",
            "اللهم صلِّ على محمد وعلى آل محمد كما صليت على إبراهيم وعلى آل إبراهيم إنك حميد مجيد",
            "قال رسول الله صلى الله عليه وسلم: من صلى عليَّ صلاةً صلى الله عليه بها عشرًا",
            "اللهم صلِّ وسلِّم على نبينا محمد عدد خلقك ورضا نفسك وزنة عرشك ومداد كلماتك",
            "إِنَّ اللَّهَ وَمَلَائِكَتَهُ يُصَلُّونَ عَلَى النَّبِيِّ ۚ يَا أَيُّهَا الَّذِينَ آمَنُوا صَلُّوا عَلَيْهِ وَسَلِّمُوا تَسْلِيمًا",
            "اللهم صلِّ على سيدنا محمد النبي الأمي وعلى آله وصحبه وسلِّم",
            "قال رسول الله صلى الله عليه وسلم: أكثروا الصلاة عليَّ يوم الجمعة",
            "اللهم صلِّ على سيدنا محمد صلاةً تنجينا بها من جميع الأهوال والآفات",
            "اللهم صلِّ وسلِّم على سيدنا محمد ما ذكره الذاكرون وغفل عن ذكره الغافلون"
    };

    private static final Random RND = new Random();
    private static int last = -1;

    /** الصيغة التالية: المفضلة إن اختار المستخدم صيغة، وإلا تبديل عشوائي. */
    public static String next(Prefs p) {
        int f = p.formula();
        if (f >= 0 && f < LIST.length) return LIST[f];
        return next();
    }

    public static String next() {
        int i;
        do {
            i = RND.nextInt(LIST.length);
        } while (i == last && LIST.length > 1);
        last = i;
        return LIST[i];
    }
}
